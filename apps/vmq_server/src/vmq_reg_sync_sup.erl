-module(vmq_reg_sync_sup).

-behaviour(supervisor).

%% API
-export([start_link/0]).

%% Supervisor callbacks
-export([init/1]).

%%%===================================================================
%%% API functions
%%%===================================================================

start_link() ->
    supervisor:start_link({local, ?MODULE}, ?MODULE, []).

%%%===================================================================
%%% Supervisor callbacks
%%%===================================================================

init([]) ->
    NumShards = vmq_reg_sync:num_shards(),
    Children = [
        {vmq_reg_sync:shard_name(Id),
         {vmq_reg_sync, start_link, [Id]},
         permanent, 5000, worker, [vmq_reg_sync]}
        || Id <- lists:seq(0, NumShards - 1)
    ],
    {ok, {{one_for_one, 5, 10}, Children}}.
